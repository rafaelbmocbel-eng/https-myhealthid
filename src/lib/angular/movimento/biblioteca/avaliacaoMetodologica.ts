export type Item = readonly [ResultadoItem] | readonly [ResultadoItem, string];

interface Base {
  /** Nome curto (autor e ano) para a tabela. */
  rotulo: string;
  desenho: string;
  /** O que foi lido: o resumo, ou os métodos e as limitações do texto completo do PubMed Central. */
  lido: 'resumo' | 'texto_completo';
  nivelQualidade: NivelQualidade;
  decisao: DecisaoFonte;
  limitacoes: string[];
  aplicabilidade: { grau: GrauAplicabilidade; nota: string };
  /** Uma frase, exibida no laudo ao lado de "Qualidade metodológica". Sem verbo causal nem juízo sobre o corpo. */
  limitacaoPrincipal: string;
  justificativa: string;
}

export interface AvaliacaoRevisao extends Base {
  tipo: 'revisao';
  itens: Record<ChaveItemRevisao | 'veiculo', Item>;
}

export interface AvaliacaoPrimario extends Base {
  tipo: 'primario';
  itens: Record<ChaveItemPrimario | 'veiculo', Item>;
}

